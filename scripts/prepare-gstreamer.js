import { readFileSync, writeFileSync, readdirSync, existsSync } from "fs";
import { join, resolve } from "path";

// 1. Setup paths
const srcTauriDir = resolve("src-tauri");
const runtimeDir = join(srcTauriDir, "gstreamer-runtime");

if (!existsSync(runtimeDir)) {
  console.error(`Error: Custom GStreamer runtime directory not found at: ${runtimeDir}`);
  process.exit(1);
}

const libGstDir = join(runtimeDir, "lib", "gstreamer-1.0");
const libGioDir = join(runtimeDir, "lib", "gio", "modules");

// 2. Scan folders for DLLs
const coreDlls = existsSync(runtimeDir) 
  ? readdirSync(runtimeDir).filter(f => f.endsWith(".dll")) 
  : [];
const pluginDlls = existsSync(libGstDir) 
  ? readdirSync(libGstDir).filter(f => f.endsWith(".dll")) 
  : [];
const gioDlls = existsSync(libGioDir) 
  ? readdirSync(libGioDir).filter(f => f.endsWith(".dll")) 
  : [];

console.log(`Found ${coreDlls.length} core DLLs, ${pluginDlls.length} plugins, and ${gioDlls.length} GIO modules.`);

if (coreDlls.length === 0) {
  console.error("Warning: No core DLLs found in the root of gstreamer-runtime folder.");
}

// 3. Generate NSIS Hooks (src-tauri/gstreamer-hooks.nsi)
const nsiContent = `; Generated by scripts/prepare-gstreamer.js
!macro NSIS_HOOK_POSTINSTALL
  SetOutPath "$INSTDIR"
  File "${runtimeDir}\\*.dll"
  
  SetOutPath "$INSTDIR\\lib\\gstreamer-1.0"
  File "${libGstDir}\\*.dll"
  
  SetOutPath "$INSTDIR\\lib\\gio\\modules"
  File "${libGioDir}\\*.dll"
!macroend

!macro NSIS_HOOK_PREUNINSTALL
  Delete "$INSTDIR\\*.dll"
  RMDir /r "$INSTDIR\\lib"
!macroend
`;

writeFileSync(join(srcTauriDir, "gstreamer-hooks.nsi"), nsiContent, "utf8");
console.log("Generated src-tauri/gstreamer-hooks.nsi");

// 4. Generate WiX Fragment (src-tauri/gstreamer-fragment.wxs)
const wixSafeId = (prefix, filename) => {
  return (prefix + "_" + filename.replace(/[^a-zA-Z0-9_.]/g, "_")).substring(0, 72);
};

let coreComponents = [];
let pluginComponents = [];
let gioComponents = [];
let componentRefs = [];

// Core DLLs
for (const file of coreDlls) {
  const compId = wixSafeId("comp_bin", file);
  const fileId = wixSafeId("file_bin", file);
  const fullPath = join(runtimeDir, file);
  coreComponents.push(`      <Component Id="${compId}" Guid="*">
        <File Id="${fileId}" Source="${fullPath}" KeyPath="yes" />
      </Component>`);
  componentRefs.push(compId);
}

// Plugin DLLs
for (const file of pluginDlls) {
  const compId = wixSafeId("comp_lib_gst", file);
  const fileId = wixSafeId("file_lib_gst", file);
  const fullPath = join(libGstDir, file);
  pluginComponents.push(`            <Component Id="${compId}" Guid="*">
              <File Id="${fileId}" Source="${fullPath}" KeyPath="yes" />
            </Component>`);
  componentRefs.push(compId);
}

// GIO Module DLLs
for (const file of gioDlls) {
  const compId = wixSafeId("comp_lib_gio", file);
  const fileId = wixSafeId("file_lib_gio", file);
  const fullPath = join(libGioDir, file);
  gioComponents.push(`                <Component Id="${compId}" Guid="*">
                  <File Id="${fileId}" Source="${fullPath}" KeyPath="yes" />
                </Component>`);
  componentRefs.push(compId);
}

const wxsContent = `<?xml version="1.0" encoding="utf-8"?>
<Wix xmlns="http://schemas.microsoft.com/wix/2006/wi">
  <Fragment>
    <DirectoryRef Id="INSTALLDIR">
      <!-- Core bin DLLs -->
${coreComponents.join("\n")}

      <!-- Library subdirectories -->
      <Directory Id="dir_lib" Name="lib">
        <!-- GStreamer 1.0 Plugins -->
        <Directory Id="dir_gstreamer_1_0" Name="gstreamer-1.0">
${pluginComponents.join("\n")}
        </Directory>
        
        <!-- GIO modules -->
        <Directory Id="dir_gio" Name="gio">
          <Directory Id="dir_modules" Name="modules">
${gioComponents.join("\n")}
          </Directory>
        </Directory>
      </Directory>
    </DirectoryRef>
  </Fragment>
</Wix>
`;

writeFileSync(join(srcTauriDir, "gstreamer-fragment.wxs"), wxsContent, "utf8");
console.log("Generated src-tauri/gstreamer-fragment.wxs");

// 5. Update src-tauri/tauri.conf.json
const tauriConfPath = join(srcTauriDir, "tauri.conf.json");
const tauriConf = JSON.parse(readFileSync(tauriConfPath, "utf8"));

if (!tauriConf.bundle) {
  tauriConf.bundle = {};
}
if (!tauriConf.bundle.windows) {
  tauriConf.bundle.windows = {};
}

// NSIS config
if (!tauriConf.bundle.windows.nsis) {
  tauriConf.bundle.windows.nsis = {};
}
tauriConf.bundle.windows.nsis.installerHooks = "gstreamer-hooks.nsi";

// WiX config
if (!tauriConf.bundle.windows.wix) {
  tauriConf.bundle.windows.wix = {};
}
tauriConf.bundle.windows.wix.fragmentPaths = ["gstreamer-fragment.wxs"];
tauriConf.bundle.windows.wix.componentRefs = componentRefs;

writeFileSync(tauriConfPath, JSON.stringify(tauriConf, null, 2), "utf8");
console.log("Updated src-tauri/tauri.conf.json successfully with custom GStreamer configuration!");
